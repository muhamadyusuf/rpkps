function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

/**
 * Tautan yang tampil seperti tombol.
 *
 * Sengaja BUKAN `<Button render={<Link />}>`: primitif Button milik Base UI
 * memasang `role="button"` pada elemen non-`<button>`, sehingga pembaca layar
 * mengumumkan tautan navigasi sebagai tombol dan afordansi tautan hilang —
 * buka di tab baru, salin alamat, daftar tautan. Menyetel `nativeButton={false}`
 * hanya membungkam peringatannya, tidak memperbaiki semantiknya.
 *
 * Untuk href yang bukan halaman (mis. endpoint unduhan), sertakan
 * `prefetch={false}` supaya Next tidak memanggil endpoint itu lebih dulu.
 */
function ButtonLink({
  className,
  variant = "default",
  size = "default",
  ...props
}: React.ComponentProps<typeof Link> & VariantProps<typeof buttonVariants>) {
  return (
    <Link
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

export { Button, ButtonLink, buttonVariants }
